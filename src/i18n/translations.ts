export function detectTextDirection(text: string, fallback: 'rtl' | 'ltr' = 'ltr'): 'rtl' | 'ltr' {
  if (!text || !text.trim()) return fallback;
  const hebrewRegex = /[\u0590-\u05FF]/;
  const latinRegex = /[A-Za-z]/;
  for (const ch of text) {
    if (hebrewRegex.test(ch)) return 'rtl';
    if (latinRegex.test(ch)) return 'ltr';
  }
  return fallback;
}

